"""Build the film timeline from lines.json and the measured voice durations.

Writes timeline.json (for mix.py and srt) and timeline.js (loaded by index.html).
Scene = 15 s unless the dialogue + question card need more. Card appears after the last
line + a reaction beat, and stays at least as long as the reading-time rule needs
(characters / 15 + 1.5 s, DIRECTOR.md §7), never less than 4.4 s.
"""
import json, os, sys, re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lines = json.load(open(os.path.join(HERE, 'lines.json'), encoding='utf-8'))
durp = os.path.join(HERE, 'voice', 'dur.json')
dur = json.load(open(durp)) if os.path.exists(durp) else {}

CARDS = {
 1: ["Apa yang membuat pembaca", "percaya pada sebuah skripsi?"],
 2: ["Bagian mana bisa dipadatkan agar", "persoalan utama segera terlihat?"],
 3: ["Apakah temuan menarik selalu", "merupakan jawaban penelitian?"],
 4: ["Apa yang dapat dipahami setelah", "sumber-sumber itu dibaca bersama?"],
 5: ["Bagaimana pilihan bahan dapat", "memengaruhi gambaran hasil?"],
 6: ["Seberapa jauh bukti ini mendukung", "kalimat di atasnya?"],
 7: ["Jika tabel dihapus,", "pesan apa yang hilang?"],
 8: ["Penjelasan apa yang belum diberikan", "oleh deskripsi kejadian?"],
 9: ["Apa perbedaan temuan,", "implikasi, dan usulan?"],
 10: ["Apakah istilah ini memperjelas", "makna atau menutupinya?"],
 11: ["Bisakah pembaca menemukan kembali", "bukti yang kamu gunakan?"],
 12: ["Temukan satu bagian yang belum", "selaras dalam drafmu. Tuliskan", "perbaikan dan alasannya."],
}
LEAD = 0.6          # first line starts this long after the cut
GAP = 0.35          # silence between lines
REACT = 0.55        # Vidka's wordless reaction before the card
MIN_SCENE = 15.0
MIN_CARD = 4.4
# extra beats inside a scene: {scene: {line id: extra pause before it}}
BEFORE = {'s12d': 0.8}          # the silence before Vidka's most important line

def est(text):
    return 0.3 + 0.062 * len(text)

scenes = []
T = 0.0
out_lines = []
for sc in range(1, 13):
    ls = [l for l in lines if l['scene'] == sc]
    t = T + LEAD
    for l in ls:
        t += BEFORE.get(l['id'], 0)
        d = dur.get(l['id'], est(l['text']))
        out_lines.append({**l, 't': round(t, 3), 'd': round(d, 3), 'scene_t0': round(T, 3)})
        t += d + GAP
    last_end = t - GAP
    card_t = max(last_end + REACT, T + 9.6)
    chars = sum(len(re.sub(r'\s', '', s)) for s in CARDS[sc])
    hold = max(MIN_CARD, chars / 15 + 1.5 + 0.4)
    if sc == 12:
        hold += 1.5                      # the final task card stays longer; the credit line comes under it
    end = max(T + MIN_SCENE, card_t + hold)
    scenes.append({'n': sc, 't0': round(T, 3), 't1': round(end, 3), 'card': round(card_t, 3),
                   'last_end': round(last_end, 3), 'q': CARDS[sc]})
    T = end

tl = {'dur': round(T, 3), 'scenes': scenes, 'lines': out_lines, 'measured': bool(dur)}
json.dump(tl, open(os.path.join(HERE, 'timeline.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
open(os.path.join(HERE, 'timeline.js'), 'w', encoding='utf-8').write(
    '// generated by tools/timeline.py — do not edit\nwindow.TL = ' + json.dumps(tl, ensure_ascii=False) + ';\n')
print('timeline: %.2f s, %d scenes, %d lines, durations %s' % (T, len(scenes), len(out_lines), 'measured' if dur else 'ESTIMATED'))
for s in scenes:
    print('  scene %2d  %6.2f–%6.2f  card at %6.2f (%.1f s)' % (s['n'], s['t0'], s['t1'], s['card'], s['t1'] - s['card']))
